CREATE TABLE library_members (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    type  VARCHAR(255) NOT NULL,
    CONSTRAINT library_member_email UNIQUE (email)
);

CREATE TABLE books (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(255) NOT NULL,
    author         VARCHAR(255) NOT NULL,
    genre          VARCHAR(255) NOT NULL,
    isbn           VARCHAR(255) NOT NULL,
    published_year INTEGER NOT NULL,
    lifecycle      VARCHAR(255) NOT NULL,
    CONSTRAINT book_isbn UNIQUE (isbn)
);

CREATE TABLE borrowers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    email       VARCHAR(255) NOT NULL UNIQUE,
    borrow_date TIMESTAMP,
    return_date TIMESTAMP
);

CREATE TABLE book_copies (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode        VARCHAR(255) NOT NULL,
    is_available   BOOLEAN NOT NULL,
    times_borrowed INTEGER NOT NULL,
    condition      VARCHAR(255) NOT NULL,
    acquired_date  DATE NOT NULL,
    book_id        BIGINT NOT NULL REFERENCES books (id),
    owner_id       BIGINT NOT NULL REFERENCES library_members (id),
    visibility     VARCHAR(255) NOT NULL,
    CONSTRAINT book_copy_barcode UNIQUE (barcode)
);

CREATE TABLE borrowings (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id      BIGINT NOT NULL REFERENCES books (id),
    book_copy_id BIGINT NOT NULL REFERENCES book_copies (id),
    borrower_id  BIGINT NOT NULL REFERENCES borrowers (id),
    borrow_date  DATE NOT NULL,
    return_date  DATE,
    due_date     DATE NOT NULL,
    status       VARCHAR(20) NOT NULL,
    late_fee     NUMERIC(10, 2)
);